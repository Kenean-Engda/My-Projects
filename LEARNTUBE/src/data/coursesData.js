const levels = ["beginner", "intermediate", "advanced"];

export const allCourseIds = [];
COURSES_DATA.forEach((topic) => {
  const courses = topic?.courses;
  const topicCourseIds = [];
  levels.forEach((level) => {
    const levelCourses = courses?.[level];
    const levelVideos = levelCourses?.videos || [];
    const levelPlaylists = levelCourses?.playlists || [];
    const levelIds = [];
    levelVideos.forEach((course) => {
      levelIds.push(course?.courseId);
    });
    levelPlaylists.forEach((course) => {
      levelIds.push(course?.courseId);
    });
    topicCourseIds.push(...levelIds);
  });
  const filteredIds = topicCourseIds.filter((item) => typeof item === "string");
  allCourseIds.push(...filteredIds);
});
